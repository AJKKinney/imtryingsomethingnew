import { readFileSync } from 'node:fs'
import { describe, expect, it } from 'vitest'
import {
  ROADMAP_REGIONS, WHOLE_FILES, extract, renderRoadmap, splice,
} from '../../tools/gendocs.ts'
import { DECISIONS } from '../../src/data/decisions.ts'
import { CANONICAL_HOMES, DELIVERABLES, EA_PHASES, PHASE_ORDER, estimate } from '../../src/data/plan.ts'

const root = new URL('../../', import.meta.url)
const read = (path: string): string => readFileSync(new URL(path, root), 'utf8')

// A-002 · phase 1 · tier build · cadence push · source §63.3
// why: transcription across twenty memoryless sessions is exactly the mechanism by which
// a specification and its code diverge. The appendix inverted the source of truth; these
// four inherit the property, and §136.5 is why they had to: an artifact that is READ may
// be prose, and an artifact that is EXECUTED must be generated.
describe('A-002 · §63.3 no generated document can drift', () => {
  for (const file of WHOLE_FILES) {
    it(`${file.path} matches what the generator emits, byte for byte`, () => {
      expect(read(file.path)).toBe(file.render())
    })
  }
})

// A-003 · phase 1 · tier build · cadence push · source §147.2
// why: ROADMAP.md is generated by §136.2, read as a SOURCE by §145.6, and hand-written by
// §63.4's IN PROGRESS: block — one file on three sides of the same graph. A generator that
// rewrote it would clobber the only thing that lets the next session recover, and a hand
// edit inside a generated region would be silently reverted by the next run. So the check
// runs BOTH ways, which is the same shape §71.2 already runs for assertions.
describe('A-003 · §147.2 sentinels, enforced in both directions', () => {
  const roadmap = read('ROADMAP.md')

  it('encloses every whole-file document in its own region', () => {
    for (const file of WHOLE_FILES) {
      const text = read(file.path)
      expect(text.startsWith('<!-- BEGIN GENERATED:'), `${file.path} opens outside a region`).toBe(true)
      expect(text.trimEnd().endsWith('-->'), `${file.path} closes outside a region`).toBe(true)
    }
  })

  it('direction one — a hand edit INSIDE a region fails', () => {
    for (const [id, render] of Object.entries(ROADMAP_REGIONS)) {
      const onDisk = extract(roadmap, id)
      expect(onDisk, `ROADMAP.md is missing the region "${id}"`).toBeDefined()
      expect(onDisk?.trim(), `${id} has been hand-edited`).toBe(render().trim())
    }
    // And the failure is real rather than assumed: a planted edit must be detected.
    const tampered = splice(roadmap, 'roadmap-run', '## The run\n\nnothing happens')
    expect(extract(tampered, 'roadmap-run')?.trim()).not.toBe(extract(roadmap, 'roadmap-run')?.trim())
  })

  it('direction two — a generator writing OUTSIDE its region fails', () => {
    // The authored text is everything the sentinels do not cover, and it must survive a
    // regeneration byte for byte. This is the direction that protects IN PROGRESS:.
    const authored = (source: string): string => {
      let out = source
      for (const id of Object.keys(ROADMAP_REGIONS)) out = splice(out, id, '')
      return out
    }
    expect(authored(renderRoadmap(roadmap))).toBe(authored(roadmap))
  })

  it('keeps the IN PROGRESS: block and the feedback log outside every region', () => {
    // §63.4's exit protocol names both, so both are things a session WRITES.
    for (const authoredMarker of ['## IN PROGRESS:', '## Feedback log']) {
      const at = roadmap.indexOf(authoredMarker)
      expect(at, `ROADMAP.md has no ${authoredMarker}`).toBeGreaterThan(-1)
      for (const id of Object.keys(ROADMAP_REGIONS)) {
        const body = extract(roadmap, id) ?? ''
        expect(body.includes(authoredMarker), `${id} swallowed ${authoredMarker}`).toBe(false)
      }
    }
  })
})

// A-046 · phase 1 · tier build · cadence push · source §84.1, §75.3
// why: §84.1 found the index 46% out of date eight passes after it was built, and fixed
// the cause rather than the contents — the index is the SOURCE. A decision that is not
// here is not settled, and that is the only thing standing between a memoryless session
// and §75.1's eleven confidently-wrong answers.
describe('A-046 · §84.1 a decision is not settled until it is indexed', () => {
  it('names a current owner, citing a section or a commit, for every decision', () => {
    // A commit is a citation too, and deliberately so: a decision found while building
    // is still a decision, and §84.1's rule is that the index is the SOURCE rather than
    // a summary of the plan. Two entries here are owned by commit 8 for that reason —
    // the clock's home and input quantisation were settled by a circular import and a
    // replay-size measurement, neither of which any section could have anticipated.
    for (const d of DECISIONS) {
      expect(d.owner, `${d.topic} has no owner`).toMatch(/§\d+|commit \d+/)
      expect(d.decision.length, `${d.topic}'s decision is too thin to act on`).toBeGreaterThan(40)
    }
  })

  it('lets no two decisions claim the same topic', () => {
    // Two entries owning one topic is the state that produced §58, §59, §60 and §61:
    // two sections each believing the other is authoritative.
    const seen = new Map<string, string>()
    for (const d of DECISIONS) {
      const prior = seen.get(d.topic)
      expect(prior, `"${d.topic}" is claimed by both ${prior} and ${d.owner}`).toBeUndefined()
      seen.set(d.topic, d.owner)
    }
  })

  it('points supersession forward, never at itself', () => {
    for (const d of DECISIONS) {
      if (d.supersedes === undefined) continue
      expect(d.supersedes.includes(d.owner), `${d.topic} supersedes itself`).toBe(false)
    }
  })

  it('lists every decision in the generated index', () => {
    const doc = read('DECISIONS.md')
    for (const d of DECISIONS) expect(doc, `${d.topic} is missing from the index`).toContain(d.topic)
  })
})

// A-047 · phase 1 · tier build · cadence push · source §145.6
// why: §21 stated 19-24 sessions while its own rows summed to 20-26, and twenty passes
// then added 7.3-10.6 sessions of scope while declaring the total unchanged. An addition
// measured against the total never moves it. So the total is emitted from the items, and
// a hand-written one cannot survive a regeneration.
describe('A-047 · §145.6 the schedule is emitted from its items', () => {
  it('sums the phases to the stated totals rather than restating them', () => {
    const perPhase = PHASE_ORDER.reduce(
      (acc, p) => {
        const items = DELIVERABLES.filter((d) => d.phase === p)
        return {
          low: acc.low + items.reduce((n, d) => n + d.low, 0),
          high: acc.high + items.reduce((n, d) => n + d.high, 0),
        }
      },
      { low: 0, high: 0 },
    )
    const all = estimate(PHASE_ORDER)
    expect(Math.abs(all.low - perPhase.low)).toBeLessThan(1e-9)
    expect(Math.abs(all.high - perPhase.high)).toBeLessThan(1e-9)
  })

  it('gives every deliverable a phase, a band and the pass that added it', () => {
    for (const d of DELIVERABLES) {
      expect(d.high, `${d.what} has an inverted band`).toBeGreaterThanOrEqual(d.low)
      expect(d.low, `${d.what} is free`).toBeGreaterThan(0)
      expect(d.source, `${d.what} names no pass`).toMatch(/§\d+/)
    }
  })

  it('prints the emitted totals into ROADMAP.md and nothing else', () => {
    const region = extract(read('ROADMAP.md'), 'roadmap-schedule') ?? ''
    const ea = estimate(EA_PHASES)
    const all = estimate(PHASE_ORDER)
    expect(region).toContain(`**${ea.low}–${ea.high}**`)
    expect(region).toContain(`**${all.low}–${all.high}**`)
  })
})

// A-048 · phase 1 · tier build · cadence push · source §135.4, §75.2
// why: six canonical homes were created to make something readable and none was ever
// re-measured; the resume set reached x5.3 its stated budget, with src/data/ alone three
// times the whole of it. A home is a budget, not just a location.
describe('A-048 · §135.4 a canonical home is a budget', () => {
  it('declares a token ceiling for every home', () => {
    for (const h of CANONICAL_HOMES) {
      expect(h.tokenCeiling, `${h.file} has no ceiling`).toBeGreaterThan(0)
      expect(h.source, `${h.file} cites no section`).toMatch(/§\d+/)
    }
  })

  it('actually generates every home it calls generated', () => {
    const generatedPaths = new Set(WHOLE_FILES.map((f) => f.path))
    for (const h of CANONICAL_HOMES) {
      if (!h.generated) continue
      const isWholeFile = generatedPaths.has(h.file)
      const isRegioned = h.file === 'ROADMAP.md' && Object.keys(ROADMAP_REGIONS).length > 0
      expect(isWholeFile || isRegioned, `${h.file} claims to be generated and nothing emits it`).toBe(true)
    }
  })

  it('keeps the resume set inside the sum of its ceilings', () => {
    // §135.3's partitioned figure is 12,502 tokens. The ceilings are per home and the
    // sweep reports them; what is checked here is that the list is bounded at all,
    // because §63.4 costed the resume set once and nothing measured it for 72 passes.
    const total = CANONICAL_HOMES.reduce((n, h) => n + h.tokenCeiling, 0)
    expect(total).toBeLessThanOrEqual(20_000)
  })
})
